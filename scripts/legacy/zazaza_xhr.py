import requests
import re

HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
    "Accept-Language": "ru,en;q=0.9",
}

print("=" * 70)
print("ZazaZa: XHR ENDPOINT DEEP ANALYSIS")
print("=" * 70)

r = requests.get("https://a.zazaza.me/list?sort=updated", headers=HEADERS, timeout=20)
html = r.text

# 1. ???? ??? ??????? ? src (??????? JS ?????)
print("\n[1] ??????? JS ???????:")
external_scripts = re.findall(r'<script[^>]+src="([^"]+)"', html)
print(f"??????? {len(external_scripts)} ??????? ????????:")
for script in external_scripts[:10]:
    print(f"  {script[:120]}")

# 2. ???? ??? URL ? /api/ ??? /catalog/ ? HTML
print("\n[2] ??? URL ???????? ? HTML:")
all_urls = re.findall(r'(?:https?:)?//[a-z0-9\.\-]+/[a-zA-Z0-9/\.\-_]+', html)
unique_patterns = {}
for url in all_urls:
    # ?????????? ?? ?????? ? ??????? ???????? ????
    match = re.match(r'(?:https?:)?//([a-z0-9\.\-]+)/([a-zA-Z]+)', url)
    if match:
        domain, path = match.groups()
        key = f"{domain}/{path}"
        unique_patterns[key] = unique_patterns.get(key, 0) + 1

print("???-15 URL ????????? ?? ??????/????:")
for pattern, count in sorted(unique_patterns.items(), key=lambda x: -x[1])[:15]:
    print(f"  {count:3d}x {pattern}")

# 3. ???? rm.one-way.work (?????????? CDN)
print("\n[3] ??? URL ? rm.one-way.work:")
one_way_urls = re.findall(r'https?://[a-z0-9\.\-]*one-way\.work/[^"\'\s<>]+', html)
for url in list(set(one_way_urls))[:20]:
    print(f"  {url[:150]}")

# 4. ??????? ????? API endpoints ?? one-way.work
print("\n[4] ????????? ????????? API endpoints ?? one-way.work:")
test_endpoints = [
    "https://rm.one-way.work/api/catalog",
    "https://rm.one-way.work/api/list",
    "https://rm.one-way.work/api/updates",
    "https://rm.one-way.work/api/latest",
    "https://rm.one-way.work/catalog",
    "https://rm.one-way.work/list",
    "https://resrm.one-way.work/api",
]

for url in test_endpoints:
    try:
        r = requests.get(url, headers=HEADERS, timeout=10)
        ct = r.headers.get("content-type", "")[:30]
        print(f"  [{r.status_code}] {url} ({len(r.content)} bytes, {ct})")
        if r.status_code == 200 and "json" in ct:
            print(f"    JSON preview: {r.text[:200]}")
    except Exception as e:
        print(f"  [ERROR] {url}: {type(e).__name__}")

# 5. ???? JSON ?????? ?????? inline ???????? (?????? ASCII)
print("\n[5] Inline ??????? ? ??????? (?????? ASCII ????????):")
scripts = re.findall(r'<script[^>]*>(.*?)</script>', html, re.DOTALL)
print(f"????? inline ????????: {len(scripts)}")

# ???? ???????? ??????
for i, script in enumerate(scripts):
    if len(script) > 100:
        # ???? ???????? JSON ? ??????? ? ?????
        has_title_data = any(kw in script.lower() for kw in ['title', 'manga', 'chapter', 'cover'])
        if has_title_data:
            print(f"  Script #{i+1} ({len(script)} bytes) - has title data")
            print(f"    Preview: {script[:200]}")

# 6. ???? fetch/XMLHttpRequest/axios ? ????????
print("\n[6] ???? fetch/XHR/axios ??????:")
for i, script in enumerate(scripts):
    if any(kw in script for kw in ['fetch(', 'axios.', 'XMLHttpRequest', 'api.']):
        print(f"  Script #{i+1}: found XHR-related code")
        # ???? URL ? ???? ???????
        urls_in_script = re.findall(r'["\'](/[^"\'\s]{5,})["\']', script)
        if urls_in_script:
            print(f"    URLs found: {urls_in_script[:5]}")

print("\n" + "=" * 70)
