import pathlib

p = pathlib.Path("/app/docker-compose.yml")
lines = p.read_text(encoding="utf-8").splitlines(keepends=True)

# ??????? ?????? "  backend:"
backend_idx = None
for i, line in enumerate(lines):
    if line.strip() == "backend:":
        backend_idx = i
        break

if backend_idx is None:
    print("ERROR: backend: not found")
    exit(1)

print(f"Found backend: at line {backend_idx}")

# ??????? ????????? ?????? (?????? ? 2 ????????? ? ??????)
next_service_idx = None
for i in range(backend_idx + 1, len(lines)):
    line = lines[i]
    # ?????? ?? ?????? 2 ???????? (?? ??????)
    if line.startswith("  ") and not line.startswith("    ") and line.strip() and ":" in line and line.strip().split(":")[0].replace(" ", "").isalpha():
        next_service_idx = i
        break

if next_service_idx is None:
    next_service_idx = len(lines)

print(f"Next service at line {next_service_idx}")

# ???? ????? ????? "depends_on" ??? ????? ????????? ???????
# ?????????: ????????? environment ????? depends_on (???? ????) ??? ????? ????????? ???????
insert_idx = next_service_idx

# ???? depends_on ?????? backend
for i in range(backend_idx + 1, next_service_idx):
    if lines[i].strip() == "depends_on:":
        insert_idx = i
        print(f"Found depends_on at line {i}")
        break

# ????????? ??? ?? ??? TELEGRAPH_ACCESS_TOKEN
full_text = "".join(lines)
if "TELEGRAPH_ACCESS_TOKEN" in full_text:
    print("TELEGRAPH_ACCESS_TOKEN already exists")
else:
    # ????????? environment ??????
    env_block = [
        "    environment:\n",
        "      - TELEGRAPH_ACCESS_TOKEN=82dc98d2b2b08932d80c5fe2b909256544d8fa55a3a04c581881ffcb0e91\n",
    ]
    
    lines[insert_idx:insert_idx] = env_block
    print(f"? Inserted environment block at line {insert_idx}")

# ??????????
p.write_text("".join(lines), encoding="utf-8")

# ?????????? ?????????
print("\nResult (lines around backend):")
result_lines = p.read_text(encoding="utf-8").splitlines()
for i, line in enumerate(result_lines):
    if i >= backend_idx and i <= backend_idx + 30:
        print(f"{i:3d}: {line}")
